//! `klf ridl bindgen` (section 25): source-level Rust, Kira and Swift bindings.
//!
//! Rust binds every function through the C-view adapter `klf ridl adapters`
//! emits for it (see [`caller_symbol`]). Kira imports the module through
//! `@Ridl` declarations, whose adapters its compiler builds.
//!
//! The Swift subset directly binds owned scalar functions whose `ridlcc`
//! classification matches Swift's `swiftcc`. Other Swift shapes are emitted as
//! comments until their ABI or layout shims exist.

use std::fmt::Write as _;

use crate::mangle::function_symbol;
use crate::module::{
    AnnArg, AnnValue, Annotation, Convention, FunctionDecl, Item, ItemKind, Module,
};
use crate::types::{Scalar, Type};

mod kira;
mod rust;

pub use kira::kira_bindings;
pub use rust::rust_bindings;

/// The symbol of the C-view adapter `klf ridl adapters` defines for the
/// export at `path` (`name`, or `Type.name` for a method) of `module`.
#[must_use]
pub fn caller_symbol(module: &str, path: &str) -> String {
    format!("{module}_{}", path.replace('.', "_"))
}

/// Generate Swift declarations for the RIDL shapes that use Swift's scalar ABI.
#[must_use]
pub fn swift_bindings(module: &Module) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `klf ridl bindgen --lang swift`. Do not edit.\n\n");
    for import in &module.imports {
        let _ = writeln!(
            out,
            "// Unsupported RIDL import `{import}`: module resolution is not implemented."
        );
    }
    if !module.imports.is_empty() {
        out.push('\n');
    }

    for (index, item) in module.items.iter().enumerate() {
        match &item.kind {
            ItemKind::Function(function) => {
                emit_swift_function(&mut out, module, item, function, index);
            }
            ItemKind::Struct(decl) => {
                let reason = if decl.fields.is_none() {
                    "opaque ownership requires a release shim"
                } else if !decl.generics.is_empty() {
                    "generic layouts require descriptor builders"
                } else {
                    "RIDL field layout needs an explicit Swift layout shim"
                };
                emit_swift_unsupported(&mut out, "struct", &decl.name, reason);
            }
            ItemKind::Enum(decl) => {
                let reason = if decl.generics.is_empty() {
                    "RIDL tag and payload layout needs an explicit Swift layout shim"
                } else {
                    "generic layouts require descriptor builders"
                };
                emit_swift_unsupported(&mut out, "enum", &decl.name, reason);
            }
            ItemKind::Trait(decl) => emit_swift_unsupported(
                &mut out,
                "trait",
                &decl.name,
                "trait objects require witness-table adapters",
            ),
            ItemKind::Extend(_) => emit_swift_unsupported(
                &mut out,
                "extend",
                &crate::emit::item_path_of(item),
                "methods and conformances require receiver or witness-table shims",
            ),
            ItemKind::Alias(decl) => emit_swift_unsupported(
                &mut out,
                "type alias",
                &decl.name,
                "alias resolution is not implemented",
            ),
            ItemKind::Const(decl) => emit_swift_unsupported(
                &mut out,
                "constant",
                &decl.name,
                "RIDL literal conversion is not implemented",
            ),
        }
    }
    out
}

fn emit_swift_function(
    out: &mut String,
    module: &Module,
    item: &Item,
    function: &FunctionDecl,
    index: usize,
) {
    let (tag, deprecated) = match swift_annotations(&item.annotations) {
        Ok(annotations) => annotations,
        Err(reason) => {
            emit_swift_unsupported(out, "function", &function.name, reason);
            return;
        }
    };
    if !is_ridl_identifier(&module.name) {
        emit_swift_unsupported(
            out,
            "function",
            &function.name,
            "module name is not a RIDL identifier, so its symbol cannot be mangled",
        );
        return;
    }
    if let Some(reason) = swift_function_reason(function) {
        emit_swift_unsupported(out, "function", &function.name, reason);
        return;
    }

    let symbol = function_symbol(&module.name, &function.name, tag.as_deref());
    let private_name = format!("__klf_ridl_{index}");
    let local_names = (0..function.params.len())
        .map(|n| format!("__ridl_arg{n}"))
        .collect::<Vec<_>>();
    let swift_types = function
        .params
        .iter()
        .map(|param| swift_value_type(&param.ty).expect("validated scalar parameter"))
        .collect::<Vec<_>>();

    let abi_params = local_names
        .iter()
        .zip(&swift_types)
        .map(|(name, ty)| format!("_ {name}: consuming {ty}"))
        .collect::<Vec<_>>()
        .join(", ");
    let public_params = function
        .params
        .iter()
        .zip(&local_names)
        .zip(&swift_types)
        .map(|((param, name), ty)| format!("{} {name}: consuming {ty}", swift_label(&param.label)))
        .collect::<Vec<_>>()
        .join(", ");
    let call_args = local_names.join(", ");
    let result_type = function.result.as_ref().and_then(swift_value_type);

    let _ = writeln!(out, "@_silgen_name(\"{symbol}\")");
    let _ = write!(out, "private func {private_name}({abi_params})");
    if let Some(result) = result_type {
        let _ = write!(out, " -> {result}");
    }
    out.push('\n');

    if let Some(message) = deprecated {
        let _ = writeln!(
            out,
            "@available(*, deprecated, message: {})",
            swift_string_literal(&message)
        );
    }
    let _ = write!(
        out,
        "public func {}({public_params})",
        swift_identifier(&function.name)
    );
    if let Some(result) = result_type {
        let _ = write!(out, " -> {result}");
    }
    let _ = writeln!(out, " {{\n    {private_name}({call_args})\n}}\n");
}

fn swift_function_reason(function: &FunctionDecl) -> Option<&'static str> {
    if function.self_param.is_some() {
        return Some("methods need a receiver shim");
    }
    if !function.generics.is_empty() {
        return Some("generic functions need descriptor arguments");
    }
    if matches!(&function.result, Some(Type::Result(_, _))) {
        return Some("failing functions need an error-register shim");
    }
    for param in &function.params {
        if param.convention != Convention::Owned {
            return Some("borrowed parameters need an address or ownership shim");
        }
        if swift_value_type(&param.ty).is_none() {
            return Some("parameter is not a directly representable Swift scalar");
        }
    }
    if let Some(result) = &function.result
        && !matches!(result, Type::Scalar(Scalar::Void))
        && swift_value_type(result).is_none()
    {
        return Some("result is not a directly representable Swift scalar");
    }
    None
}

fn swift_value_type(ty: &Type) -> Option<&'static str> {
    let Type::Scalar(scalar) = ty else {
        return None;
    };
    Some(match scalar {
        Scalar::I8 => "Int8",
        Scalar::I16 => "Int16",
        Scalar::I32 => "Int32",
        Scalar::I64 => "Int64",
        Scalar::U8 => "UInt8",
        Scalar::U16 => "UInt16",
        Scalar::U32 => "UInt32",
        Scalar::U64 => "UInt64",
        Scalar::F32 => "Float",
        Scalar::F64 => "Double",
        Scalar::Bool => "Bool",
        Scalar::ISize => "Int",
        Scalar::USize => "UInt",
        Scalar::RawPtr => "UnsafeMutableRawPointer?",
        Scalar::I128 | Scalar::U128 | Scalar::Void => return None,
    })
}

fn swift_annotations(
    annotations: &[Annotation],
) -> Result<(Option<String>, Option<String>), &'static str> {
    let mut tag = None;
    let mut deprecated = None;
    for annotation in annotations {
        match annotation.name.as_str() {
            "Abi" => {
                if tag.is_some() {
                    return Err("multiple `@Abi` annotations cannot be resolved");
                }
                let [argument] = annotation.args.as_slice() else {
                    return Err("`@Abi` needs exactly one version argument");
                };
                if argument.label.as_deref() != Some("version") {
                    return Err("`@Abi` needs a labeled `version` argument");
                }
                let AnnValue::String(version) = &argument.value else {
                    return Err("`@Abi` version must be a hexadecimal string");
                };
                if version.len() < 16
                    || version.len() > 32
                    || !version.bytes().all(|byte| byte.is_ascii_hexdigit())
                {
                    return Err("`@Abi` version must contain 16 to 32 hexadecimal digits");
                }
                tag = Some(version[..16].to_ascii_lowercase());
            }
            "Deprecated" => {
                if deprecated.is_some() {
                    return Err("multiple `@Deprecated` annotations cannot be resolved");
                }
                let [
                    AnnArg {
                        label: None,
                        value: AnnValue::String(message),
                    },
                ] = annotation.args.as_slice()
                else {
                    return Err("`@Deprecated` needs one positional string message");
                };
                deprecated = Some(message.clone());
            }
            _ => return Err("annotation is not represented by this binding subset"),
        }
    }
    Ok((tag, deprecated))
}

fn swift_string_literal(value: &str) -> String {
    let mut literal = String::from("\"");
    for character in value.chars() {
        match character {
            '\\' => literal.push_str("\\\\"),
            '"' => literal.push_str("\\\""),
            '\n' => literal.push_str("\\n"),
            '\r' => literal.push_str("\\r"),
            '\t' => literal.push_str("\\t"),
            character if character.is_control() => {
                let _ = write!(literal, "\\u{{{:X}}}", character as u32);
            }
            character => literal.push(character),
        }
    }
    literal.push('"');
    literal
}

fn is_ridl_identifier(value: &str) -> bool {
    let mut bytes = value.bytes();
    matches!(bytes.next(), Some(b'A'..=b'Z' | b'a'..=b'z' | b'_'))
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}

fn swift_identifier(value: &str) -> String {
    format!("`{value}`")
}

fn swift_label(value: &str) -> String {
    if value == "_" {
        "_".to_owned()
    } else {
        swift_identifier(value)
    }
}

fn emit_swift_unsupported(out: &mut String, kind: &str, name: &str, reason: &str) {
    let _ = writeln!(out, "// Unsupported RIDL {kind} `{name}`: {reason}.\n");
}
