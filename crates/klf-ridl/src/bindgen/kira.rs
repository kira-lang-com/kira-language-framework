//! Kira bindings: the types of a module and an `@Ridl` declaration per
//! export. The Kira compiler builds the adapter of each declaration itself
//! and links the providing library a package names in `nativeLibraries`.

use std::fmt::Write as _;

use crate::emit::type_text;
use crate::module::{
    AnnValue, Annotation, Convention, ExtendBody, FunctionDecl, ItemKind, Module, SelfParam,
    TraitDecl,
};
use crate::types::{EnumDecl, Scalar, StructDecl, Type};

/// Generate Kira declarations that import `module`.
#[must_use]
pub fn kira_bindings(module: &Module) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `klf ridl bindgen --lang kira`. Do not edit.\n\n");
    // A type another module defines is that module's, reached by importing
    // it (KLF-RIDL section 27.7), never declared again here.
    for import in &module.imports {
        let _ = writeln!(out, "import {import}");
    }
    if !module.imports.is_empty() {
        out.push('\n');
    }
    for item in &module.items {
        match &item.kind {
            ItemKind::Struct(s) => {
                out.push_str(&instances(&item.annotations));
                match conformed(module, &s.name) {
                    Some(family) => member(&mut out, s, &family),
                    None => structure(&mut out, s),
                }
            }
            ItemKind::Enum(e) => enumeration(&mut out, e),
            ItemKind::Function(f) => match function(&module.name, None, f) {
                Ok(line) => {
                    let _ = writeln!(out, "{line}\n");
                }
                Err(reason) => {
                    let _ = writeln!(out, "// skipped function `{}`: {reason}\n", f.name);
                }
            },
            ItemKind::Extend(extend) => {
                let ExtendBody::Methods(methods) = &extend.body else {
                    continue;
                };
                // A trait's defaults are its family's members without a
                // body (`family`); what else its `extend` holds are methods
                // every value of the family has, read as Kira writes them,
                // with the receiver left implicit.
                if is_trait(module, &extend.target) {
                    family_methods(&mut out, module, &extend.target, methods);
                    continue;
                }
                let owner = match owner(&extend.target) {
                    Ok(owner) => owner,
                    Err(reason) => {
                        let _ = writeln!(
                            out,
                            "// skipped methods of `{}`: {reason}\n",
                            type_text(&extend.target)
                        );
                        continue;
                    }
                };
                let _ = writeln!(out, "extend {owner} {{");
                for method in methods {
                    match function(&module.name, Some(&extend.target), method) {
                        Ok(line) => {
                            let _ = writeln!(out, "    {line}");
                        }
                        Err(reason) => {
                            let _ =
                                writeln!(out, "    // skipped method `{}`: {reason}", method.name);
                        }
                    }
                }
                out.push_str("}\n\n");
            }
            ItemKind::Trait(t) => family(&mut out, module, t),
            ItemKind::Alias(a) => match spell(&a.ty) {
                Ok(target) => {
                    let _ = writeln!(out, "type {} = {target}\n", a.name);
                }
                Err(why) => {
                    let _ = writeln!(out, "// skipped alias `{}`: {why}\n", a.name);
                }
            },
            ItemKind::Const(_) => {}
        }
    }
    constants(&mut out, module);
    out
}

/// The module's constants as `let`s, which a Kira reader writes in where it
/// reads them. A dotted name is a namespace path: `let Rights.read` is
/// `read` in `namespace Rights`.
fn constants(out: &mut String, module: &Module) {
    let mut namespaces: Vec<(String, Vec<String>)> = Vec::new();
    for item in &module.items {
        let ItemKind::Const(c) = &item.kind else {
            continue;
        };
        let text = match spell(&c.ty) {
            Ok(text) => text,
            Err(reason) => {
                let _ = writeln!(out, "// skipped constant `{}`: {reason}\n", c.name);
                continue;
            }
        };
        // A distinct is built by calling it; a scalar, a string and a
        // `Number` take the literal as written.
        let value = match &c.ty {
            Type::Nominal { name, .. } if name != "Number" && is_distinct(module, name) => {
                format!("{name}({})", c.literal)
            }
            _ => c.literal.clone(),
        };
        let (path, member) = c.name.rsplit_once('.').unwrap_or(("", &c.name));
        let line = format!("let {member}: {text} = {value}");
        match namespaces.iter_mut().find(|(known, _)| known == path) {
            Some((_, lines)) => lines.push(line),
            None => namespaces.push((path.to_owned(), vec![line])),
        }
    }
    for (path, lines) in namespaces {
        if path.is_empty() {
            for line in lines {
                let _ = writeln!(out, "{line}\n");
            }
        } else {
            let _ = writeln!(
                out,
                "namespace {path} {{\n    {}\n}}\n",
                lines.join("\n    ")
            );
        }
    }
}

/// Whether the module's struct `name` is a distinct's lowering: one `raw`
/// field of a type a distinct can wrap.
fn is_distinct(module: &Module, name: &str) -> bool {
    module.items.iter().any(|item| match &item.kind {
        ItemKind::Struct(s) if s.name == name => matches!(
            s.fields.as_deref(),
            Some([field]) if field.name == "raw" && wraps_distinct(&field.ty)
        ),
        _ => false,
    })
}

/// Whether a distinct can wrap `ty`: a scalar other than `Void`, or
/// `Number` or a sized number, which copy as trivially as a scalar
/// (KLF-RIDL §27.5).
fn wraps_distinct(ty: &Type) -> bool {
    match ty {
        Type::Scalar(scalar) => *scalar != Scalar::Void,
        Type::Nominal { name, args } => {
            args.is_empty()
                && (name == "Number" || crate::types::SIZED_NUMBERS.contains(&name.as_str()))
        }
        _ => false,
    }
}

/// The Kira spelling of `ty`.
fn spell(ty: &Type) -> Result<String, String> {
    Ok(match ty {
        Type::Scalar(scalar) => match scalar {
            Scalar::I64 | Scalar::ISize => "Int",
            Scalar::F64 => "Float",
            Scalar::U64 | Scalar::USize => "U64",
            Scalar::I8 => "I8",
            Scalar::I16 => "I16",
            Scalar::I32 => "I32",
            Scalar::U8 => "U8",
            Scalar::U16 => "U16",
            Scalar::U32 => "U32",
            Scalar::F32 => "F32",
            Scalar::Bool => "Bool",
            Scalar::RawPtr => "RawPtr",
            Scalar::Void => "Void",
            Scalar::I128 | Scalar::U128 => return Err("Kira has no 128-bit integers".to_owned()),
        }
        .to_owned(),
        Type::String => "String".to_owned(),
        Type::Array(item) => format!("[{}]", spell(item)?),
        Type::Optional(inner) => format!("Optional<{}>", spell(inner)?),
        Type::Result(ok, err) => format!("Result<{}, {}>", spell(ok)?, spell(err)?),
        Type::Nominal { name, args } if args.is_empty() => name.clone(),
        // An instance of a generic declaration, and a parameter of the one
        // it is read in, are written as Kira writes them (section 23.5).
        Type::Nominal { name, args } => format!(
            "{name}<{}>",
            args.iter()
                .map(spell)
                .collect::<Result<Vec<_>, _>>()?
                .join(", ")
        ),
        Type::Generic(name) => name.clone(),
        // Kira writes a tuple of two to four values as RIDL does.
        Type::Tuple(items) if (2..=4).contains(&items.len()) => format!(
            "({})",
            items
                .iter()
                .map(spell)
                .collect::<Result<Vec<_>, _>>()?
                .join(", ")
        ),
        Type::Tuple(_) => return Err("Kira has tuples of two to four values".to_owned()),
        // An owned closure is the same two words in both (KLF-RIDL section
        // 21.8), and Kira names a result of nothing `Void`.
        Type::Function { params, result } => format!(
            "({}) -> {}",
            params
                .iter()
                .map(spell)
                .collect::<Result<Vec<_>, _>>()?
                .join(", "),
            spell(result)?
        ),
        Type::BorrowFunction { .. } => {
            return Err("Kira borrows a closure only as a parameter".to_owned());
        }
        // A trait is a construct family, and a trait object the family's
        // value (KLF-RIDL section 27.7).
        Type::TraitObject(name) => format!("Any {name}"),
    })
}

fn structure(out: &mut String, s: &StructDecl) {
    // Kira's `Number` crosses as the two words it is; the `.ridl` declares
    // it for the layout, and Kira already has the type.
    if s.name == "Number" {
        return;
    }
    // An opaque struct is a handle to a value the defining module keeps
    // (KLF-RIDL section 21.5): one pointer to a box that carries the
    // descriptor copying and destroying it. Kira's class is that handle, so
    // the struct reads back as a class with no fields of its own.
    let Some(fields) = &s.fields else {
        if s.generics.is_empty() {
            let _ = writeln!(out, "class {} {{}}\n", s.name);
        } else {
            let _ = writeln!(
                out,
                "// skipped struct `{}`: generic types are not imported\n",
                s.name
            );
        }
        return;
    };
    // Kira lowers `distinct Name = Scalar` (or `Number`) to a struct of its one `raw`
    // field, so that struct reads back as the distinct it came from. The
    // layout and the RIDL text are the same either way.
    if let [field] = fields.as_slice()
        && field.name == "raw"
        && wraps_distinct(&field.ty)
        && let Ok(text) = spell(&field.ty)
    {
        let _ = writeln!(out, "distinct {} = {text}\n", s.name);
        return;
    }
    let mut lines = Vec::new();
    for field in fields {
        match spell(&field.ty) {
            Ok(text) => lines.push(match &field.default {
                Some(default) => format!("    var {}: {text} = {default}", field.name),
                None => format!("    var {}: {text}", field.name),
            }),
            Err(reason) => {
                let _ = writeln!(
                    out,
                    "// skipped struct `{}`: field `{}`: {reason}\n",
                    s.name, field.name
                );
                return;
            }
        }
    }
    let _ = writeln!(
        out,
        "struct {}{} {{\n{}\n}}\n",
        s.name,
        parameters(&s.generics),
        lines.join("\n")
    );
}

/// A generic declaration's parameters as Kira writes them, `<Value>`, and
/// nothing for a declaration that has none.
fn parameters(generics: &[String]) -> String {
    if generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", generics.join(", "))
    }
}

/// The `@Instance` annotations of a generic declaration, each on a line of
/// its own: the instances the defining module exports (section 23.5).
fn instances(annotations: &[Annotation]) -> String {
    let mut text = String::new();
    for annotation in annotations.iter().filter(|a| a.name == "Instance") {
        let arguments: Vec<String> = annotation
            .args
            .iter()
            .map(|arg| match &arg.value {
                AnnValue::Ident(name) => name.clone(),
                AnnValue::Type(ty) => spell(ty).unwrap_or_else(|_| type_text(ty)),
                AnnValue::String(text) => format!("{text:?}"),
            })
            .collect();
        let _ = writeln!(text, "@Instance({})", arguments.join(", "));
    }
    text
}

/// The type an `extend` adds methods to, as Kira names it: a generic
/// declaration extended over its own parameters by its name alone, as
/// `extend Holder` is in the module defining `struct Holder<Value>`.
fn owner(target: &Type) -> Result<String, String> {
    match target {
        Type::Nominal { name, args }
            if !args.is_empty() && args.iter().all(|arg| matches!(arg, Type::Generic(_))) =>
        {
            Ok(name.clone())
        }
        _ => spell(target),
    }
}

fn enumeration(out: &mut String, e: &EnumDecl) {
    if !e.generics.is_empty() {
        let _ = writeln!(
            out,
            "// skipped enum `{}`: generic enums are not imported\n",
            e.name
        );
        return;
    }
    let mut lines = Vec::new();
    for case in &e.cases {
        if case.payload.is_empty() {
            lines.push(format!("    {}", case.name));
            continue;
        }
        match case
            .payload
            .iter()
            .map(spell)
            .collect::<Result<Vec<_>, _>>()
        {
            Ok(items) => lines.push(format!("    {}({})", case.name, items.join(", "))),
            Err(reason) => {
                let _ = writeln!(
                    out,
                    "// skipped enum `{}`: case `{}`: {reason}\n",
                    e.name, case.name
                );
                return;
            }
        }
    }
    let marker = if e.open { "@Open\n" } else { "" };
    let _ = writeln!(
        out,
        "{marker}enum {} {{\n{}\n}}\n",
        e.name,
        lines.join("\n")
    );
}

/// The `@Ridl` declaration of `f`, a method of `owner` when there is one.
fn function(module: &str, owner: Option<&Type>, f: &FunctionDecl) -> Result<String, String> {
    if !f.generics.is_empty() {
        return Err("generic functions are not imported".to_owned());
    }
    let mut params = Vec::new();
    if owner.is_some() {
        match f.self_param {
            Some(SelfParam::Owned) => params.push("self".to_owned()),
            Some(SelfParam::Borrow) => params.push("borrow self".to_owned()),
            Some(SelfParam::BorrowMut) => params.push("borrow mut self".to_owned()),
            None => {}
        }
    }
    for (index, param) in f.params.iter().enumerate() {
        // The last parameter holding a family's values, owned, is the slot
        // a call's trailing block fills, as `toolbar(items: [some Widget])`
        // declares it: RIDL writes `some F` as the `Any F` it is.
        let last = index + 1 == f.params.len() && param.convention == Convention::Owned;
        let text = match (last, &param.ty) {
            (true, Type::TraitObject(held)) => format!("some {held}"),
            (true, Type::Array(element)) => match element.as_ref() {
                Type::TraitObject(held) => format!("[some {held}]"),
                _ => spell(&param.ty)?,
            },
            _ => spell(&param.ty)?,
        };
        let default = param
            .default
            .as_ref()
            .map(|value| format!(" = {value}"))
            .unwrap_or_default();
        params.push(match param.convention {
            Convention::Owned => format!("{}: {text}{default}", param.label),
            Convention::Borrow => format!("{}: borrow {text}{default}", param.label),
            Convention::BorrowMut => format!("{}: borrow mut {text}{default}", param.label),
        });
    }
    let result = match &f.result {
        None | Some(Type::Scalar(Scalar::Void)) => String::new(),
        Some(ty) => format!(" -> {}", spell(ty)?),
    };
    Ok(format!(
        "@Ridl(\"{module}\") function {}({}){result}",
        f.name,
        params.join(", ")
    ))
}

/// Whether `ty` names a trait of `module`.
fn is_trait(module: &Module, ty: &Type) -> bool {
    let (Type::Nominal { name, .. } | Type::TraitObject(name)) = ty else {
        return false;
    };
    module
        .items
        .iter()
        .any(|item| matches!(&item.kind, ItemKind::Trait(t) if t.name == *name))
}

/// The trait the module's struct `name` conforms to, if it conforms to one.
fn conformed(module: &Module, name: &str) -> Option<String> {
    module.items.iter().find_map(|item| match &item.kind {
        ItemKind::Extend(extend) => match (&extend.target, &extend.body) {
            (Type::Nominal { name: target, .. }, ExtendBody::Conformance(traits))
                if target == name =>
            {
                traits.iter().find_map(|t| match t {
                    Type::Nominal { name, .. } | Type::TraitObject(name) => Some(name.clone()),
                    _ => None,
                })
            }
            _ => None,
        },
        _ => None,
    })
}

/// A trait as the construct family it is in Kira (KLF-RIDL section 27.7).
/// A method taking nothing but `borrow self` and answering a value is a
/// value member; a method the trait's module exports a default for has no
/// body here, the default being the module's, and the rest are required.
fn family(out: &mut String, module: &Module, t: &TraitDecl) {
    if !t.generics.is_empty() || !t.assoc.is_empty() || !t.parents.is_empty() {
        let _ = writeln!(
            out,
            "// skipped trait `{}`: only a trait with methods alone is a family\n",
            t.name
        );
        return;
    }
    let defaulted: Vec<&str> = module
        .items
        .iter()
        .filter_map(|item| match &item.kind {
            ItemKind::Extend(extend) if is_trait(module, &extend.target) => {
                match (&extend.target, &extend.body) {
                    (
                        Type::Nominal { name, .. } | Type::TraitObject(name),
                        ExtendBody::Methods(methods),
                    ) if *name == t.name => Some(
                        methods
                            .iter()
                            .map(|method| method.name.as_str())
                            .collect::<Vec<_>>(),
                    ),
                    _ => None,
                }
            }
            _ => None,
        })
        .flatten()
        .collect();
    let mut lines = Vec::new();
    for method in &t.methods {
        match family_member(
            &module.name,
            method,
            defaulted.contains(&method.name.as_str()),
        ) {
            Ok(line) => lines.push(line),
            Err(reason) => {
                let _ = writeln!(
                    out,
                    "// skipped trait `{}`: method `{}`: {reason}\n",
                    t.name, method.name
                );
                return;
            }
        }
    }
    let _ = writeln!(out, "construct {} {{\n{}\n}}\n", t.name, lines.join("\n"));
}

fn family_member(module: &str, method: &FunctionDecl, defaulted: bool) -> Result<String, String> {
    if !method.generics.is_empty() {
        return Err("generic methods are not imported".to_owned());
    }
    let result = match &method.result {
        None | Some(Type::Scalar(Scalar::Void)) => None,
        Some(ty) => Some(spell(ty)?),
    };
    match (method.self_param, method.params.is_empty(), &result) {
        (Some(SelfParam::Borrow), true, Some(result)) if !defaulted => {
            return Ok(format!("    @Required let {}: {result}", method.name));
        }
        (None, _, _) => return Err("a trait method takes `self`".to_owned()),
        _ => {}
    }
    // A member that changes its value says so (KLF-RIDL section 27.7); the
    // others borrow it, which Kira leaves unwritten.
    let mut params = Vec::new();
    if method.self_param == Some(SelfParam::BorrowMut) {
        params.push("borrow mut self".to_owned());
    }
    for param in &method.params {
        let text = spell(&param.ty)?;
        params.push(match param.convention {
            Convention::Owned => format!("{}: {text}", param.label),
            Convention::Borrow => format!("{}: borrow {text}", param.label),
            Convention::BorrowMut => format!("{}: borrow mut {text}", param.label),
        });
    }
    let mut marks = Vec::new();
    if defaulted {
        marks.push(format!("@Ridl(\"{module}\")"));
    } else {
        marks.push("@Required".to_owned());
    }
    if method.self_param == Some(SelfParam::Owned) {
        marks.push("@Consuming".to_owned());
    }
    let result = result
        .map(|result| format!(" -> {result}"))
        .unwrap_or_default();
    Ok(format!(
        "    {} function {}({}){result}",
        marks.join(" "),
        method.name,
        params.join(", ")
    ))
}

/// The methods of `extend Family` that are not the trait's own members, as
/// an `extend` of the family whose receiver is implicit, as Kira writes one.
fn family_methods(out: &mut String, module: &Module, target: &Type, methods: &[FunctionDecl]) {
    let (Type::Nominal { name, .. } | Type::TraitObject(name)) = target else {
        return;
    };
    let members: Vec<&str> = module
        .items
        .iter()
        .filter_map(|item| match &item.kind {
            ItemKind::Trait(t) if t.name == *name => {
                Some(t.methods.iter().map(|method| method.name.as_str()))
            }
            _ => None,
        })
        .flatten()
        .collect();
    let mut lines = Vec::new();
    for method in methods {
        if members.contains(&method.name.as_str()) {
            continue;
        }
        // A method that changes the value spells its receiver; one that
        // borrows it leaves it implicit, as Kira writes a family's methods.
        let receiver = match method.self_param {
            Some(SelfParam::Borrow) => None,
            Some(SelfParam::BorrowMut) => Some(target),
            _ => {
                lines.push(format!(
                    "    // skipped method `{}`: a family's method borrows its value",
                    method.name
                ));
                continue;
            }
        };
        match function(&module.name, receiver, method) {
            Ok(line) => lines.push(format!("    {line}")),
            Err(reason) => lines.push(format!("    // skipped method `{}`: {reason}", method.name)),
        }
    }
    if lines.is_empty() {
        return;
    }
    let _ = writeln!(out, "extend {name} {{\n{}\n}}\n", lines.join("\n"));
}

/// How a slot of type `ty` holding `family`'s values is spelled: `Any F`
/// holds one and `[Any F]` several, as a construct's `let content: some F`
/// and `let children: [some F]` do. A field holding values of another
/// family, as a link's `value: Any NavigationValue`, is an input.
fn slot(ty: &Type, family: &str) -> Option<String> {
    let ours = |held: &str| held.rsplit('.').next() == family.rsplit('.').next();
    match ty {
        Type::TraitObject(held) if ours(held) => Some(format!("some {held}")),
        Type::Array(element) => match element.as_ref() {
            Type::TraitObject(held) if ours(held) => Some(format!("[some {held}]")),
            _ => None,
        },
        _ => None,
    }
}

/// A struct conforming to a trait as a declaration of the trait's family:
/// its fields are the construct's inputs, with their defaults, except a
/// field holding the family's values with no default, which is a slot the
/// trailing content of a call fills (section 27.7), declared in the body, and
/// one holding them after it, which is a slot with a default.
fn member(out: &mut String, s: &StructDecl, family: &str) {
    let Some(fields) = s.fields.as_ref() else {
        let _ = writeln!(
            out,
            "// skipped struct `{}`: a family's declaration has fields\n",
            s.name
        );
        return;
    };
    let mut inputs = Vec::new();
    let mut slots = Vec::new();
    for field in fields {
        if field.default.is_none()
            && let Some(held) = slot(&field.ty, family)
        {
            slots.push(format!("    let {}: {held}", field.name));
            continue;
        }
        // A field after the first slot is declared in the body too, so the
        // construct's fields keep the contract's order, which is its layout.
        // One there holding the family's values is a slot with a default,
        // which a labelled block fills, as `header: { ... }` does.
        let body = !slots.is_empty();
        if body && let (Some(held), Some(default)) = (slot(&field.ty, family), &field.default) {
            slots.push(format!("    let {}: {held} = {default}", field.name));
            continue;
        }
        match spell(&field.ty) {
            Ok(text) if body => slots.push(match &field.default {
                Some(default) => format!("    let {}: {text} = {default}", field.name),
                None => format!("    let {}: {text}", field.name),
            }),
            Ok(text) => inputs.push(match &field.default {
                Some(default) => format!("{}: {text} = {default}", field.name),
                None => format!("{}: {text}", field.name),
            }),
            Err(reason) => {
                let _ = writeln!(
                    out,
                    "// skipped struct `{}`: field `{}`: {reason}\n",
                    s.name, field.name
                );
                return;
            }
        }
    }
    let body = if slots.is_empty() {
        String::new()
    } else {
        format!("\n{}\n", slots.join("\n"))
    };
    let _ = writeln!(
        out,
        "construct {}{}({}) extends {family} {{{body}}}\n",
        s.name,
        parameters(&s.generics),
        inputs.join(", ")
    );
}
