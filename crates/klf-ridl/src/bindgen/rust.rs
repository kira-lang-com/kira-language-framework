//! Rust bindings (section 25.1): `#[repr(C)]` types with RIDL layout, and a
//! safe function per export that calls the export's C-view adapter.
//!
//! In the C view a scalar travels by value, any other value and every
//! `borrow mut` by address, and a non-scalar result is written through a
//! leading address. An owned value passed by address is moved: the callee
//! takes it over and the caller forgets it.

mod prelude;

use std::fmt::Write as _;

use super::caller_symbol;
use crate::layout::LayoutEngine;
use crate::mangle::descriptor_symbol;
use crate::module::{Convention, ExtendBody, FunctionDecl, ItemKind, Module, SelfParam};
use crate::types::{Decl, EnumDecl, Registry, Scalar, StructDecl, Type};
use prelude::PRELUDE;

/// Generate a Rust binding module for `module`. Link the object of
/// `klf ridl adapters` for the same file, and the providing library.
#[must_use]
pub fn rust_bindings(module: &Module) -> String {
    let registry = module.registry();
    let bindings = Bindings {
        module,
        registry: &registry,
        engine: LayoutEngine::new(&registry, 8),
    };
    let mut out = String::new();
    out.push_str("// Generated by `klf ridl bindgen`. Do not edit.\n");
    out.push_str(PRELUDE);
    for item in &module.items {
        match &item.kind {
            ItemKind::Struct(s) => bindings.structure(&mut out, s),
            ItemKind::Enum(e) => bindings.enumeration(&mut out, e),
            ItemKind::Function(f) => bindings.function(&mut out, None, f),
            ItemKind::Extend(extend) => {
                if let ExtendBody::Methods(methods) = &extend.body {
                    for method in methods {
                        bindings.function(&mut out, Some(&extend.target), method);
                    }
                }
            }
            ItemKind::Trait(t) => {
                let _ = writeln!(
                    out,
                    "// skipped trait `{}`: trait objects need witness tables\n",
                    t.name
                );
            }
            ItemKind::Alias(a) => match bindings.spell(&a.ty) {
                Ok(text) => {
                    let _ = writeln!(out, "pub type {} = {text};\n", a.name);
                }
                Err(reason) => {
                    let _ = writeln!(out, "// skipped alias `{}`: {reason}\n", a.name);
                }
            },
            ItemKind::Const(c) => match bindings.spell(&c.ty) {
                Ok(text) if matches!(c.ty, Type::Scalar(_)) => {
                    // The contract's own spelling, which callers read in
                    // its docs, rather than Rust's SCREAMING_CASE.
                    let name = c.name.replace('.', "_");
                    let _ = writeln!(
                        out,
                        "#[allow(non_upper_case_globals)]\npub const {name}: {text} = {};\n",
                        c.literal
                    );
                }
                _ => {
                    let _ = writeln!(
                        out,
                        "// skipped constant `{}`: only scalars are bound\n",
                        c.name
                    );
                }
            },
        }
    }
    out
}

struct Bindings<'a> {
    module: &'a Module,
    registry: &'a Registry,
    engine: LayoutEngine<'a>,
}

impl Bindings<'_> {
    /// The Rust spelling of `ty` as it sits in memory.
    fn spell(&self, ty: &Type) -> Result<String, String> {
        Ok(match ty {
            Type::Scalar(Scalar::Void) => "()".to_owned(),
            Type::Scalar(scalar) => rust_scalar(*scalar).to_owned(),
            Type::String => "RidlString".to_owned(),
            Type::Array(item) => format!("RidlBuffer<{}>", self.spell(item)?),
            Type::Optional(inner) => {
                if self.has_niche(ty) {
                    return Err(format!(
                        "`{}` uses the pointer niche",
                        crate::emit::type_text(ty)
                    ));
                }
                format!("RidlOptional<{}>", self.spell(inner)?)
            }
            Type::Result(ok, err) => {
                format!("RidlResult<{}, {}>", self.spell(ok)?, self.spell(err)?)
            }
            Type::Tuple(items) if items.is_empty() => "()".to_owned(),
            Type::Tuple(_) => return Err("tuples have no Rust layout binding".to_owned()),
            Type::Nominal { name, args } => {
                match self.registry.get(name) {
                    Some(Decl::Enum(e)) if e.open => {
                        return Err(format!(
                            "open enum `{name}` can hold cases Rust does not know"
                        ));
                    }
                    Some(_) => {}
                    None => return Err(format!("`{name}` is not declared in this module")),
                }
                if self.has_niche(ty) {
                    return Err(format!("`{name}` uses the pointer niche"));
                }
                if args.is_empty() {
                    name.clone()
                } else {
                    let args = args
                        .iter()
                        .map(|a| self.spell(a))
                        .collect::<Result<Vec<_>, _>>()?;
                    format!("{name}<{}>", args.join(", "))
                }
            }
            Type::Generic(name) => name.clone(),
            Type::Function { .. } | Type::BorrowFunction { .. } => {
                return Err("closures need a context adapter".to_owned());
            }
            Type::TraitObject(name) => return Err(format!("`Any {name}` needs a witness table")),
        })
    }

    fn has_niche(&self, ty: &Type) -> bool {
        let concrete = match ty {
            Type::Nominal { name, args } if args.is_empty() => {
                matches!(self.registry.get(name), Some(Decl::Enum(e)) if e.generics.is_empty())
            }
            Type::Optional(_) => true,
            _ => false,
        };
        concrete && matches!(self.engine.enum_shape(ty), Ok(Some(shape)) if shape.niche)
    }

    fn structure(&self, out: &mut String, s: &StructDecl) {
        let generics = generics_text(&s.generics);
        let Some(fields) = &s.fields else {
            let descriptor = descriptor_symbol(&self.module.name, &s.name);
            let name = &s.name;
            let _ = writeln!(
                out,
                "/// An opaque handle; dropping it destroys the value through its descriptor.\n\
                 #[repr(transparent)]\n#[derive(Debug)]\n\
                 pub struct {name}(pub core::ptr::NonNull<core::ffi::c_void>);\n\n\
                 unsafe extern \"C\" {{\n    #[link_name = \"{descriptor}\"]\n    \
                 static {name}_DESCRIPTOR: RidlDescriptor;\n}}\n\n\
                 impl Drop for {name} {{\n    fn drop(&mut self) {{\n        \
                 unsafe {{\n            if let Some(destroy) = {name}_DESCRIPTOR.destroy {{\n                \
                 destroy((&raw mut self.0).cast());\n            }}\n        }}\n    }}\n}}\n"
            );
            return;
        };
        let mut lines = Vec::new();
        for field in fields {
            match self.spell(&field.ty) {
                Ok(text) => lines.push(format!("    pub {}: {text},", identifier(&field.name))),
                Err(reason) => {
                    let _ = writeln!(
                        out,
                        "// skipped struct `{}`: field `{}`: {reason}\n",
                        s.name, field.name
                    );
                    return;
                }
            }
        }
        let _ = writeln!(
            out,
            "#[repr(C)]\n#[derive(Clone, Debug)]\npub struct {}{generics} {{",
            s.name
        );
        for line in lines {
            let _ = writeln!(out, "{line}");
        }
        out.push_str("}\n\n");
    }

    fn enumeration(&self, out: &mut String, e: &EnumDecl) {
        if e.open {
            let _ = writeln!(
                out,
                "// skipped enum `{}`: an open enum can hold cases Rust does not know\n",
                e.name
            );
            return;
        }
        if e.generics.is_empty() && self.has_niche(&Type::nominal(&e.name)) {
            let _ = writeln!(
                out,
                "// skipped enum `{}`: it uses the pointer niche\n",
                e.name
            );
            return;
        }
        let tag = match e.cases.len() {
            0..=256 => "u8",
            257..=65_536 => "u16",
            _ => "u32",
        };
        let payloads = e.cases.iter().any(|case| !case.payload.is_empty());
        let mut lines = Vec::new();
        for case in &e.cases {
            if case.payload.is_empty() {
                lines.push(format!("    {},", case.name));
                continue;
            }
            let mut items = Vec::new();
            for ty in &case.payload {
                match self.spell(ty) {
                    Ok(text) => items.push(text),
                    Err(reason) => {
                        let _ = writeln!(
                            out,
                            "// skipped enum `{}`: case `{}`: {reason}\n",
                            e.name, case.name
                        );
                        return;
                    }
                }
            }
            lines.push(format!("    {}({}),", case.name, items.join(", ")));
        }
        let repr = if payloads {
            format!("C, {tag}")
        } else {
            tag.to_owned()
        };
        let generics = generics_text(&e.generics);
        let _ = writeln!(
            out,
            "#[repr({repr})]\n#[derive(Clone, Debug)]\npub enum {}{generics} {{",
            e.name
        );
        for line in lines {
            let _ = writeln!(out, "{line}");
        }
        out.push_str("}\n\n");
    }

    fn function(&self, out: &mut String, owner: Option<&Type>, f: &FunctionDecl) {
        let path = match owner {
            Some(Type::Nominal { name, .. }) => format!("{name}.{}", f.name),
            _ => f.name.clone(),
        };
        match self.signature(owner, f) {
            Ok(signature) => {
                let symbol = caller_symbol(&self.module.name, &path);
                let _ = writeln!(
                    out,
                    "unsafe extern \"C\" {{\n    fn {symbol}({}){};\n}}\n",
                    signature.external, signature.external_result
                );
                let body = format!(
                    "    pub fn {}({}){} {{\n{}    }}\n",
                    identifier(&f.name),
                    signature.parameters.join(", "),
                    signature.result,
                    signature.body(&symbol)
                );
                if let Some(Type::Nominal { name, .. }) = owner {
                    let _ = writeln!(out, "impl {name} {{\n{body}}}\n");
                } else {
                    let _ = writeln!(
                        out,
                        "{}",
                        body.lines()
                            .map(|l| l.strip_prefix("    ").unwrap_or(l))
                            .collect::<Vec<_>>()
                            .join("\n")
                    );
                    out.push('\n');
                }
            }
            Err(reason) => {
                let _ = writeln!(out, "// skipped function `{path}`: {reason}\n");
            }
        }
    }

    fn signature(&self, owner: Option<&Type>, f: &FunctionDecl) -> Result<Signature, String> {
        if !f.generics.is_empty() {
            return Err("generic functions need descriptors".to_owned());
        }
        let mut signature = Signature::default();
        let mut externals = Vec::new();
        if let Some(result) = f
            .result
            .as_ref()
            .filter(|r| !matches!(r, Type::Scalar(Scalar::Void)))
        {
            let text = self.spell(result)?;
            if let Type::Scalar(_) = result {
                signature.result = format!(" -> {text}");
                signature.external_result = format!(" -> {text}");
            } else {
                externals.push(format!("result: *mut {text}"));
                signature.arguments.push("out.as_mut_ptr()".to_owned());
                signature.slot = Some(text);
                signature.finish = match result {
                    Type::Result(ok, err) => {
                        signature.result =
                            format!(" -> Result<{}, {}>", self.spell(ok)?, self.spell(err)?);
                        ".into_result()"
                    }
                    Type::Optional(inner) => {
                        signature.result = format!(" -> Option<{}>", self.spell(inner)?);
                        ".into_option()"
                    }
                    _ => {
                        signature.result = format!(" -> {}", self.spell(result)?);
                        ""
                    }
                };
            }
        }
        if let (Some(receiver), Some(owner)) = (&f.self_param, owner) {
            let text = self.spell(owner)?;
            let convention = match receiver {
                SelfParam::Owned => Convention::Owned,
                SelfParam::Borrow => Convention::Borrow,
                SelfParam::BorrowMut => Convention::BorrowMut,
            };
            signature.parameters.push(
                match convention {
                    Convention::Owned => "self",
                    Convention::Borrow => "&self",
                    Convention::BorrowMut => "&mut self",
                }
                .to_owned(),
            );
            signature.pass(&mut externals, "self", "this", &text, convention, owner);
        }
        for param in &f.params {
            let text = self.spell(&param.ty)?;
            let name = identifier(&param.label);
            signature
                .parameters
                .push(match (param.convention, &param.ty) {
                    (Convention::BorrowMut, _) => format!("{name}: &mut {text}"),
                    (Convention::Borrow, ty) if !matches!(ty, Type::Scalar(_)) => {
                        format!("{name}: &{text}")
                    }
                    _ => format!("{name}: {text}"),
                });
            signature.pass(
                &mut externals,
                &name,
                &name,
                &text,
                param.convention,
                &param.ty,
            );
        }
        signature.external = externals.join(", ");
        Ok(signature)
    }
}

#[derive(Default)]
struct Signature {
    /// Parameters of the safe function.
    parameters: Vec<String>,
    /// ` -> T` of the safe function.
    result: String,
    /// Parameters of the adapter, and ` -> T` for a scalar result.
    external: String,
    external_result: String,
    /// Statements before the call, and the adapter's arguments.
    setup: Vec<String>,
    arguments: Vec<String>,
    /// The type of the result slot, and the conversion of what it holds.
    slot: Option<String>,
    finish: &'static str,
}

impl Signature {
    fn pass(
        &mut self,
        externals: &mut Vec<String>,
        name: &str,
        external: &str,
        text: &str,
        convention: Convention,
        ty: &Type,
    ) {
        let scalar = matches!(ty, Type::Scalar(_));
        match convention {
            Convention::BorrowMut => {
                externals.push(format!("{external}: *mut {text}"));
                self.arguments.push(format!("{name} as *mut {text}"));
            }
            _ if scalar => {
                externals.push(format!("{external}: {text}"));
                self.arguments.push(name.to_owned());
            }
            Convention::Borrow => {
                externals.push(format!("{external}: *const {text}"));
                self.arguments.push(format!("{name} as *const {text}"));
            }
            Convention::Owned => {
                externals.push(format!("{external}: *const {text}"));
                let moved = format!("moved_{}", name.trim_start_matches("r#"));
                self.setup
                    .push(format!("let {moved} = ManuallyDrop::new({name});"));
                self.arguments
                    .push(format!("&raw const *{moved} as *const {text}"));
            }
        }
    }

    fn body(&self, symbol: &str) -> String {
        let mut text = String::new();
        for line in &self.setup {
            let _ = writeln!(text, "        {line}");
        }
        let call = format!("{symbol}({})", self.arguments.join(", "));
        match &self.slot {
            Some(slot) => {
                let _ = writeln!(
                    text,
                    "        let mut out = MaybeUninit::<{slot}>::uninit();"
                );
                let _ = writeln!(
                    text,
                    "        unsafe {{\n            {call};\n            out.assume_init(){}\n        }}",
                    self.finish
                );
            }
            None => {
                let _ = writeln!(text, "        unsafe {{ {call} }}");
            }
        }
        text
    }
}

fn generics_text(generics: &[String]) -> String {
    if generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", generics.join(", "))
    }
}

/// `name`, raw when Rust reserves it.
fn identifier(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "box", "break", "const", "continue", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod",
        "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "try", "type",
        "unsafe", "use", "where", "while", "yield",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

fn rust_scalar(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::I8 => "i8",
        Scalar::I16 => "i16",
        Scalar::I32 => "i32",
        Scalar::I64 => "i64",
        Scalar::I128 => "i128",
        Scalar::U8 => "u8",
        Scalar::U16 => "u16",
        Scalar::U32 => "u32",
        Scalar::U64 => "u64",
        Scalar::U128 => "u128",
        Scalar::F32 => "f32",
        Scalar::F64 => "f64",
        Scalar::Bool => "bool",
        Scalar::ISize => "isize",
        Scalar::USize => "usize",
        Scalar::RawPtr => "*mut core::ffi::c_void",
        Scalar::Void => "()",
    }
}
