//! The `extern "C"` face of the definition-facing kernel services.
//!
//! The list mirrors `kernel/services.manifest` minus the services the native
//! runtime implements directly. Every symbol here is a thin shim: it widens
//! its arguments to words and hands the call to [`crate::services::dispatch`],
//! which routes it to the service table the frontend driver installed for the
//! phase currently running. With no table installed — a plain native program
//! that merely links the runtime — each one answers with the error sentinel,
//! exactly as the link-time stubs it replaces did.

macro_rules! services {
    ($($symbol:ident, ($($argument:ident),*), $result:ident;)*) => {
        /// Each shim's place in [`SYMBOLS`], which is how it finds its
        /// handler without hashing its name on every call.
        #[allow(non_camel_case_types, clippy::upper_case_acronyms)]
        #[derive(Clone, Copy)]
        enum Service {
            $($symbol),*
        }

        /// Every shim's symbol, in [`Service`] order.
        pub(crate) const SYMBOLS: &[&str] = &[$(stringify!($symbol)),*];

        $(services!(@shim $symbol, ($($argument),*), $result);)*
    };
    (@shim $symbol:ident, ($($argument:ident),*), i64) => {
        #[unsafe(no_mangle)]
        pub extern "C-unwind" fn $symbol($($argument: i64),*) -> i64 {
            crate::services::dispatch(Service::$symbol as usize, &[$($argument as u64),*])
        }
    };
    (@shim $symbol:ident, ($($argument:ident),*), void) => {
        #[unsafe(no_mangle)]
        pub extern "C-unwind" fn $symbol($($argument: i64),*) {
            crate::services::dispatch(Service::$symbol as usize, &[$($argument as u64),*]);
        }
    };
}

