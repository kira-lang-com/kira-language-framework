use tir_diag::{Area, Code, Diagnostic, Dialect};
use tir_format::FunctionBody;

const VFY2: Code = Code::new(Dialect::Tvisa, Area::Verifier, 2);

pub(super) fn verify_function(body: &FunctionBody) -> Vec<Diagnostic> {
    body.blocks
        .iter()
        .flat_map(|block| &block.instructions)
        .filter(|instruction| !is_tvisa_opcode(&instruction.opcode))
        .map(|instruction| {
            Diagnostic::error(
                VFY2,
                format!("instruction {} is not part of TVISA", instruction.opcode),
            )
            .with_primary_span(instruction.span)
        })
        .collect()
}

