#[test]
fn compiled_kira_phase_body_builds_a_session_module() {
    let target = "aarch64-apple-darwin"
        .parse::<klf_target::Target>()
        .expect("valid target");
    let mut image_session = Session::new(target.clone());
    let module = KiraDefinition
        .compile(
            &mut image_session,
            "definition.klfd",
            SOURCE,
            "Definition",
            target.clone(),
        )
        .unwrap_or_else(|| panic!("Kira definition lowers: {:?}", image_session.diagnostics()));
    assert_eq!(image_session.diagnostics(), []);
    let image = DefinitionImage::new(LanguageDescriptor::minimal("calc", &["calc"]), module)
        .expect("Kira definition image validates");
    let mut session = Session::new(target);
    let definition =
        ExecutableDefinition::with_executor(image, BackendDefinitionExecutor::new(Backend::Vm));
    let execution_target = session.target().clone();
    let result = definition
        .compile(
            &mut session,
            "input.calc",
            "helper main narrow caller sum2 call2 pair_sum pair_i32 Pair Zero One enum_tag Payload enum_payload enum_dispatch Record value_field struct_read enum_dispatch2 kind struct_sum struct_call enum_sum enum_call void_sink Inner nested_field nested_copy StructPayload enum_struct_copy void_sink_i32 ArrayRecord array_field EnumArray enum_array_copy array_sum void_array_sink",
            "Main",
            execution_target,
        )
        .unwrap_or_else(|| panic!("Kira definition executes: {:?}", session.diagnostics()));
    assert_eq!(
        run(&result, "main", &[5], Backend::Vm).expect("Kira-built module runs"),
        klf_vm::Outcome::Return(Some(42))
    );
}
